def active_windows(today: Optional[datetime.date] = None):
    today = today or datetime.date.today()
    out = []
    for w in WINDOWS:
        active, days, span = w.status(today)
        out.append({
            "key": w.key, "title": w.title, "active": active,
            "days_to_next": days, "span": span,
            "affected": w.affected, "hypothesis": w.hypothesis,
            "confidence": w.confidence,
        })
    out.sort(key=lambda r: (not r["active"], r["days_to_next"] if r["days_to_next"] is not None else 9999))
    return out


def calendar_context(today: Optional[datetime.date] = None):
    today = today or datetime.date.today()
    jy, jm, jd = to_jalali_date(today)
    return {
        "jalali": "%04d/%02d/%02d" % (jy, jm, jd),
        "month_name": JMONTHS[jm - 1],
        "fiscal_quarter": (jm - 1) // 3 + 1,
        "days_into_fiscal_year": (today - to_gregorian_date(jy, 1, 1)).days,
        "windows": active_windows(today),
        "codal": CODAL_DEADLINES,
        "structural": [{"title": s.title, "typical": s.typical,
                        "mechanism": s.mechanism, "evidence": s.evidence,
                        "watch": s.watch} for s in STRUCTURAL],
    }
